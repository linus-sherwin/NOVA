use serde::{Deserialize, Serialize};
use std::path::Path;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum FileCategory {
    Video,
    Image,
    Audio,
    Archive,
    Document,
    Application,
    Code,
    Cache,
    Log,
    Other,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum CleanupType {
    UserCache,
    BrowserCache,
    DeveloperCache,
    LogsAndCrashReports,
    TemporaryFiles,
    XcodeDerivedData,
    XcodeArchives,
    HomebrewCache,
    PackageCaches,
    Other,
}

impl FileCategory {
    pub fn from_extension(ext: Option<&str>) -> Self {
        match ext {
            Some(e) => match e {
                "mp4" | "mov" | "mkv" | "avi" | "webm" | "m4v" | "flv" | "wmv" => FileCategory::Video,
                "jpg" | "jpeg" | "png" | "heic" | "webp" | "gif" | "svg" | "tiff" | "bmp" | "raw" | "cr2" | "nef" => FileCategory::Image,
                "mp3" | "wav" | "flac" | "aac" | "m4a" | "ogg" | "aiff" | "wma" => FileCategory::Audio,
                "zip" | "tar" | "gz" | "bz2" | "xz" | "7z" | "dmg" | "iso" | "pkg" | "rar" | "tgz" => FileCategory::Archive,
                "pdf" | "docx" | "doc" | "xlsx" | "xls" | "pptx" | "ppt" | "pages" | "numbers" | "keynote" | "txt" | "rtf" => FileCategory::Document,
                "app" => FileCategory::Application,
                "rs" | "ts" | "tsx" | "js" | "jsx" | "py" | "go" | "c" | "cpp" | "h" | "swift" | "java" | "json" | "yaml" | "toml" | "html" | "css" => FileCategory::Code,
                "log" | "crash" | "diag" => FileCategory::Log,
                _ => FileCategory::Other,
            },
            None => FileCategory::Other,
        }
    }
}

/// Identifies if a path belongs to an identifiable cleanup opportunity.
pub fn classify_cleanup_path<P: AsRef<Path>>(path: P) -> Option<(CleanupType, &'static str, &'static str)> {
    let p = path.as_ref();
    let path_str = p.to_string_lossy();

    if path_str.contains("/Developer/Xcode/DerivedData") {
        return Some((
            CleanupType::XcodeDerivedData,
            "Xcode DerivedData",
            "Build artifacts and intermediate indexes generated by Xcode.",
        ));
    }
    if path_str.contains("/Developer/Xcode/Archives") {
        return Some((
            CleanupType::XcodeArchives,
            "Xcode Archives",
            "Past application builds and app store archives.",
        ));
    }
    if path_str.contains("/Caches/Homebrew") {
        return Some((
            CleanupType::HomebrewCache,
            "Homebrew Cache",
            "Downloaded bottle archives and build dependencies.",
        ));
    }
    if path_str.contains("/Caches/com.apple.Safari") {
        return Some((
            CleanupType::BrowserCache,
            "Safari Web Cache",
            "Temporary web images and page caches. Does not include cookies or passwords.",
        ));
    }
    if path_str.contains("/Caches/Google/Chrome") {
        return Some((
            CleanupType::BrowserCache,
            "Chrome Web Cache",
            "Chrome disk and media cache. Passwords and browsing history are untouched.",
        ));
    }
    if path_str.contains("/Caches/Firefox") {
        return Some((
            CleanupType::BrowserCache,
            "Firefox Cache",
            "Firefox offline web cache and thumbnails.",
        ));
    }
    if path_str.contains("/.npm") || path_str.contains("/Caches/npm") || path_str.contains("/Caches/pnpm") || path_str.contains("/Caches/Yarn") || path_str.contains("/.cargo/registry/cache") {
        return Some((
            CleanupType::PackageCaches,
            "Package Manager Caches",
            "Cached tarballs and packages for npm, pnpm, Yarn, or Cargo.",
        ));
    }
    if path_str.contains("/Library/Logs") {
        return Some((
            CleanupType::LogsAndCrashReports,
            "Application Logs",
            "Historical log files and diagnostic crash reports.",
        ));
    }
    if path_str.contains("/Library/Caches") {
        return Some((
            CleanupType::UserCache,
            "User Application Caches",
            "Cached data stored by macOS applications that can be safely regenerated.",
        ));
    }

    None
}

